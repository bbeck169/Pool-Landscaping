"""Phase I1.5.d · Feb-2026 — Preset registry drift guard.

Re-runs the ``scripts.dump_theme_presets`` generator into a
tempdir and asserts the output matches the checked-in
``frontend/src/theme/presets.js`` byte-for-byte. Any drift — a
backend preset edit that wasn't accompanied by a re-dump, or a
hand-edit to the frontend file — fails the suite loudly.

Complements the vitest ``test/theme-preset-parity.test.js`` guard
by locking the *generator output shape* (not just the semantic
data). If the two go out of sync (e.g. a contributor edited the
Python registry but only regenerated the JSON without also
updating the header format), CI catches it here.
"""
from __future__ import annotations

import tempfile
from pathlib import Path

from scripts.dump_theme_presets import DEFAULT_OUT, render_presets_js


def test_i15d_dump_matches_checked_in_presets_js():
    """Rendering the generator right now must exactly equal the
    checked-in ``frontend/src/theme/presets.js``.

    Fix on failure:
        cd /app/backend && python3 -m scripts.dump_theme_presets
    """
    rendered = render_presets_js()
    checked_in = DEFAULT_OUT.read_text(encoding="utf-8")
    if rendered != checked_in:
        # Emit a compact diff line-count summary so the failure
        # message is greppable — don't dump both blobs into the
        # pytest output.
        with tempfile.NamedTemporaryFile(
                mode="w", suffix=".js", delete=False, encoding="utf-8") as tf:
            tf.write(rendered)
            tmp = tf.name
        assert False, (
            f"Preset registry drift detected between backend "
            f"``services/theme/presets.py`` and checked-in "
            f"``{DEFAULT_OUT}``.\n"
            f"Regenerate with:\n"
            f"  cd /app/backend && python3 -m scripts.dump_theme_presets\n"
            f"(Rendered dump: {tmp})"
        )


def test_i15d_dump_is_idempotent():
    """Rendering the generator twice must produce byte-identical
    output — no non-deterministic serialization (dict ordering,
    timestamp, etc.)."""
    a = render_presets_js()
    b = render_presets_js()
    assert a == b


def test_i15d_dump_includes_autogenerated_header():
    """The rendered output must start with the ``AUTOGENERATED``
    warning so future contributors don't hand-edit it."""
    rendered = render_presets_js()
    assert "AUTOGENERATED" in rendered.splitlines()[1]
    assert "dump_theme_presets" in rendered


def test_i15d_dump_contains_all_31_presets():
    """The rendered output must include every registry key so
    the parity guard also catches ``missing key`` drift."""
    from services.theme.presets import PRESETS
    rendered = render_presets_js()
    for key in PRESETS:
        assert f'"{key}"' in rendered, key
