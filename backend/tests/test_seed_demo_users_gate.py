"""SEC-001 · Demo-seed gate + rotation-script idempotency tests."""
from __future__ import annotations
import asyncio, os, sys, subprocess
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND_ROOT))
ROTATE = BACKEND_ROOT / "scripts" / "rotate_demo_passwords.py"


def test_seed_landscaping_user_short_circuits_when_flag_off(monkeypatch):
    from dotenv import load_dotenv
    load_dotenv(BACKEND_ROOT / ".env")
    monkeypatch.setenv("SEED_DEMO_USERS", "0")

    import seed as seed_mod
    from motor.motor_asyncio import AsyncIOMotorClient
    client = AsyncIOMotorClient(os.environ["MONGO_URL"])
    db_local = client[os.environ["DB_NAME"]]

    async def _run():
        # Snapshot demo user count before.
        before = await db_local.users.count_documents(
            {"email": {"$in": ["admin@aquaterra.com", "mike@aquaterra.com",
                                 "customer@aquaterra.com"]}})
        # Call the seed function directly — should short-circuit with a
        # warning, no writes.
        await seed_mod.seed_landscaping_user()
        after = await db_local.users.count_documents(
            {"email": {"$in": ["admin@aquaterra.com", "mike@aquaterra.com",
                                 "customer@aquaterra.com"]}})
        client.close()
        return before, after
    before, after = asyncio.run(_run())
    assert before == after, "SEED_DEMO_USERS=0 must not create demo users"


def test_rotation_script_is_idempotent():
    """Two consecutive runs succeed and produce the standard file header.

    After rotation, restore all demo passwords to `password123` so
    downstream tests in this suite (which pre-date the rotation script
    and hard-code the dev password) keep working. Production is
    protected by SEED_DEMO_USERS=0 — the demo users don't exist there.
    """
    for _ in range(2):
        r = subprocess.run([sys.executable, str(ROTATE)],
                            capture_output=True, text=True,
                            cwd=str(BACKEND_ROOT), timeout=45)
        assert r.returncode == 0, f"rotate script failed: {r.stderr}"
        assert "Rotated" in r.stdout
    creds = Path("/app/memory/test_credentials.md").read_text(encoding="utf-8")
    assert "Regenerated by rotate_demo_passwords.py" in creds

    # Restore dev-known passwords so downstream tests still authenticate.
    from dotenv import load_dotenv
    load_dotenv(BACKEND_ROOT / ".env")
    from utils import hash_password
    from motor.motor_asyncio import AsyncIOMotorClient

    async def _restore():
        c = AsyncIOMotorClient(os.environ["MONGO_URL"])
        db = c[os.environ["DB_NAME"]]
        for e in ["super@aquaterra.com", "admin@aquaterra.com",
                   "mike@aquaterra.com", "carlos@aquaterra.com",
                   "customer@aquaterra.com"]:
            await db.users.update_one({"email": e},
                {"$set": {"password_hash": hash_password("password123"),
                          "failed_login_attempts": 0, "lockout_until": None,
                          "active": True}})
        c.close()
    asyncio.run(_restore())
