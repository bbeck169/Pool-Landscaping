#!/usr/bin/env python3
"""Phase I1.5.d · Feb-2026 — Client-side preset registry generator.

Emits ``frontend/src/theme/presets.js`` from
``backend/services/theme/presets.py`` so the two registries can
never drift structurally.

The generated file is exactly the shape the existing FE consumers
already import (``CLIENT_PRESETS`` object + ``getClientPreset``
helper) — this replaces the hand-maintained mirror that shipped
in I1.5.c with a re-runnable dump. The parity contract is enforced
by ``tests/test_i15d_preset_parity_via_dump.py`` (the dump into a
tempdir must equal the checked-in file byte-for-byte).

Usage::

    cd /app/backend && python3 -m scripts.dump_theme_presets

    # Or to a custom output path:
    cd /app/backend && python3 -m scripts.dump_theme_presets \
        --out /tmp/presets.js

The output file is prefixed with an AUTOGENERATED header so
future contributors know not to edit it by hand.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

# The generator does not need any DB / env — pure code emit.
from services.theme.presets import PRESETS


DEFAULT_OUT = (
    Path(__file__).resolve().parents[2] / "frontend" / "src" / "theme"
    / "presets.js"
)


HEADER = """\
/**
 * ⚠️  AUTOGENERATED — DO NOT EDIT BY HAND.
 *
 * Regenerate with:
 *   cd /app/backend && python3 -m scripts.dump_theme_presets
 *
 * Source of truth: ``backend/services/theme/presets.py``
 *
 * Structural parity with the backend registry is contract-locked
 * in two places:
 *   1. Vitest — ``test/theme-preset-parity.test.js`` diffs this
 *      file against a Python subprocess dump of ``PRESETS``.
 *   2. Pytest — ``tests/test_i15d_preset_parity_via_dump.py`` re-
 *      runs this generator into a tempdir and asserts the output
 *      matches this file byte-for-byte. CI catches any drift.
 *
 * Consumers: ``useTenantTheme`` uses the ``default`` entry as its
 * offline fallback when GET /api/tenants/me/theme errors before
 * the app can paint. Every other consumer should reach the live
 * registry via GET /api/theme-presets or the tenant-persisted
 * theme.
 */
"""


FOOTER = """\
export function getClientPreset(key) {
  const entry = CLIENT_PRESETS[key];
  if (!entry) return JSON.parse(JSON.stringify(CLIENT_PRESETS.default));
  return JSON.parse(JSON.stringify(entry));
}
"""


def render_presets_js() -> str:
    """Return the full text of ``presets.js`` matching the existing
    layout (2-space indent, one entry per key, JSON-quoted keys)."""
    body = json.dumps(PRESETS, indent=2, sort_keys=False)
    return (
        HEADER
        + "export const CLIENT_PRESETS = "
        + body
        + ";\n\n"
        + FOOTER
    )


def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", type=Path, default=DEFAULT_OUT,
                     help=f"Output path (default: {DEFAULT_OUT}).")
    return p.parse_args()


def main() -> int:
    args = _parse_args()
    rendered = render_presets_js()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(rendered, encoding="utf-8")
    print(f"Wrote {args.out} ({len(rendered)} chars, "
          f"{len(PRESETS)} presets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
