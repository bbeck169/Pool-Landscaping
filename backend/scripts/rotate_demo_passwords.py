#!/usr/bin/env python3
"""SEC-001 hotfix · Rotate demo-user passwords.

Rotates all 5 seeded demo accounts (super_admin, admin, pool_tech,
landscape_tech, customer) to a fresh `secrets.token_urlsafe(24)` value
per user, updates `db.users`, and rewrites `/app/memory/test_credentials.md`
with the new plaintext credentials + a "Regenerated by ... on <ISO>" header.

Only runs on explicit invocation; NEVER on boot.

    cd /app/backend && python3 scripts/rotate_demo_passwords.py
"""
from __future__ import annotations
import asyncio, os, secrets, sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from dotenv import load_dotenv
load_dotenv(Path(__file__).resolve().parent.parent / ".env")

from motor.motor_asyncio import AsyncIOMotorClient  # noqa: E402
from utils import hash_password  # noqa: E402

DEMO_EMAILS = [
    ("super@aquaterra.com",     "super_admin"),
    ("admin@aquaterra.com",     "admin"),
    ("mike@aquaterra.com",      "pool_tech"),
    ("carlos@aquaterra.com",    "landscape_tech"),
    ("customer@aquaterra.com",  "customer"),
]

CREDS_PATH = Path("/app/memory/test_credentials.md")


async def _rotate() -> list[tuple[str, str, str, bool]]:
    client = AsyncIOMotorClient(os.environ["MONGO_URL"])
    db = client[os.environ["DB_NAME"]]
    out = []
    for email, role_hint in DEMO_EMAILS:
        existing = await db.users.find_one({"email": email}, {"_id": 0, "id": 1, "role": 1})
        if not existing:
            out.append((email, role_hint, "", False))
            continue
        new_pw = secrets.token_urlsafe(24)
        await db.users.update_one(
            {"id": existing["id"]},
            {"$set": {
                "password_hash": hash_password(new_pw),
                "failed_login_attempts": 0,
                "lockout_until": None,
                "active": True,
            }},
        )
        out.append((email, existing.get("role") or role_hint, new_pw, True))
    client.close()
    return out


def _write_credentials(rows: list[tuple[str, str, str, bool]]) -> None:
    now = datetime.now(timezone.utc).isoformat()
    lines = [
        "# Test Credentials — Pool & Landscaping of Vistancia",
        "",
        f"> Regenerated by rotate_demo_passwords.py on {now}",
        "",
        "## Auth mechanism",
        "- POST `/api/auth/login` with `{email, password}` returns `{access_token, user}`.",
        "- Tokens are Bearer JWTs — send `Authorization: Bearer <token>` on every subsequent call.",
        "- Passwords below are randomly generated per rotation. Do not check into external systems.",
        "",
        "## Accounts",
    ]
    for email, role, pw, ok in rows:
        if ok:
            lines.append(f"- **{role}** · `{email}` · `{pw}`")
        else:
            lines.append(f"- **{role}** · `{email}` · _(user row not present; skipped)_")
    lines.append("")
    lines.append("## Notes")
    lines.append("- Landscape techs carry `role: \"landscape_tech\"` + `department: \"landscaping\"` and are required to")
    lines.append("  finalize their onboarding checklist before route assignment.")
    lines.append("- Emergent LLM key, Resend API key, Stripe test/live keys are in `/app/backend/.env`.")
    CREDS_PATH.parent.mkdir(parents=True, exist_ok=True)
    CREDS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    rows = asyncio.run(_rotate())
    _write_credentials(rows)
    print(f"Rotated {sum(1 for r in rows if r[3])} / {len(rows)} demo accounts.")
    for email, role, pw, ok in rows:
        if ok:
            print(f"  {role:16s} {email:32s} {pw}")
        else:
            print(f"  {role:16s} {email:32s} SKIPPED (no user row)")
    print(f"Credentials written to {CREDS_PATH}")


if __name__ == "__main__":
    main()
