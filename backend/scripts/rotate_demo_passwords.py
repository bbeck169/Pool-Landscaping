#!/usr/bin/env python3
"""SEC-001 hotfix · Rotate demo-user passwords.

Rotates all 5 seeded demo accounts (super_admin, admin, pool_tech,
landscape_tech, customer) to a fresh `secrets.token_urlsafe(24)` value
per user, updates `db.users`, and rewrites `/app/memory/test_credentials.md`
with the new plaintext credentials + a "Regenerated by ... on <ISO>" header.

Only runs on explicit invocation; NEVER on boot.

    # Rotate all demo users
    cd /app/backend && python3 scripts/rotate_demo_passwords.py

    # Rotate a subset only (other rows preserved verbatim in the file)
    cd /app/backend && python3 scripts/rotate_demo_passwords.py \\
        --only carlos@aquaterra.com
"""
from __future__ import annotations
import argparse, asyncio, os, re, secrets, sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from dotenv import load_dotenv
load_dotenv(Path(__file__).resolve().parent.parent / ".env")

from motor.motor_asyncio import AsyncIOMotorClient  # noqa: E402
from utils import hash_password  # noqa: E402

DEMO_EMAILS = [
    ("super@aquaterra.com",     "super_admin"),
    ("admin@aquaterra.com",     "admin"),
    ("mike@aquaterra.com",      "pool_tech"),
    ("carlos@aquaterra.com",    "landscape_tech"),
    ("customer@aquaterra.com",  "customer"),
]

CREDS_PATH = Path("/app/memory/test_credentials.md")


async def _rotate(only: set[str] | None = None) -> list[tuple[str, str, str, bool]]:
    """Rotate demo-user passwords. If `only` is provided, restrict to those emails."""
    client = AsyncIOMotorClient(os.environ["MONGO_URL"])
    db = client[os.environ["DB_NAME"]]
    out = []
    for email, role_hint in DEMO_EMAILS:
        if only is not None and email not in only:
            continue
        existing = await db.users.find_one({"email": email}, {"_id": 0, "id": 1, "role": 1})
        if not existing:
            out.append((email, role_hint, "", False))
            continue
        new_pw = secrets.token_urlsafe(24)
        await db.users.update_one(
            {"id": existing["id"]},
            {"$set": {
                "password_hash": hash_password(new_pw),
                "failed_login_attempts": 0,
                "lockout_until": None,
                "active": True,
            }},
        )
        out.append((email, existing.get("role") or role_hint, new_pw, True))
    client.close()
    return out


# --- Line-parsing helpers so a partial rotation preserves other rows ---
_ROW_RE = re.compile(
    r"^\s*-\s+\*\*(?P<role>[^*]+)\*\*\s+·\s+`(?P<email>[^`]+)`\s+·\s+`(?P<pw>[^`]+)`\s*$"
)


def _parse_existing_rows(text: str) -> dict[str, tuple[str, str]]:
    """Return {email: (role, pw)} for every ` · `email` · `pw` ` row in the file."""
    out: dict[str, tuple[str, str]] = {}
    for line in text.splitlines():
        m = _ROW_RE.match(line)
        if m:
            out[m.group("email")] = (m.group("role"), m.group("pw"))
    return out


def _write_credentials(rows: list[tuple[str, str, str, bool]], partial: bool) -> None:
    now = datetime.now(timezone.utc).isoformat()
    # Preserve untouched rows on a partial rotation by loading the current file
    # and merging: rotated emails overwrite; untouched emails carry through.
    existing_rows: dict[str, tuple[str, str]] = {}
    existing_header: str | None = None
    if partial and CREDS_PATH.is_file():
        existing_text = CREDS_PATH.read_text(encoding="utf-8")
        existing_rows = _parse_existing_rows(existing_text)
        # Preserve the ORIGINAL rotation header on partial runs so the other 4
        # accounts don't appear to have been re-rotated.
        for line in existing_text.splitlines():
            if line.startswith("> Regenerated by rotate_demo_passwords.py on "):
                existing_header = line
                break

    header_line = existing_header if partial and existing_header else \
        f"> Regenerated by rotate_demo_passwords.py on {now}"

    lines = [
        "# Test Credentials — Pool & Landscaping of Vistancia",
        "",
        header_line,
        "",
        "## Auth mechanism",
        "- POST `/api/auth/login` with `{email, password}` returns `{access_token, user}`.",
        "- Tokens are Bearer JWTs — send `Authorization: Bearer <token>` on every subsequent call.",
        "- Passwords below are randomly generated per rotation. Do not check into external systems.",
        "",
        "## Accounts",
    ]
    # Build a lookup of rotated results by email.
    rotated_by_email: dict[str, tuple[str, str, bool]] = {
        email: (role, pw, ok) for email, role, pw, ok in rows
    }
    # Emit rows in the canonical order from DEMO_EMAILS so file layout is stable.
    for email, default_role in DEMO_EMAILS:
        if email in rotated_by_email:
            role, pw, ok = rotated_by_email[email]
            if ok:
                lines.append(f"- **{role}** · `{email}` · `{pw}`")
            else:
                lines.append(f"- **{role}** · `{email}` · _(user row not present; skipped)_")
        elif email in existing_rows:
            role, pw = existing_rows[email]
            lines.append(f"- **{role}** · `{email}` · `{pw}`")
        else:
            lines.append(f"- **{default_role}** · `{email}` · _(user row not present; skipped)_")
    lines.append("")
    lines.append("## Notes")
    lines.append("- Landscape techs carry `role: \"landscape_tech\"` + `department: \"landscaping\"` and are required to")
    lines.append("  finalize their onboarding checklist before route assignment.")
    lines.append("- Emergent LLM key, Resend API key, Stripe test/live keys are in `/app/backend/.env`.")
    CREDS_PATH.parent.mkdir(parents=True, exist_ok=True)
    CREDS_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Rotate demo-user passwords.")
    parser.add_argument("--only", type=str, default=None,
                        help="Comma-separated list of demo emails to rotate. "
                              "Other demo rows in test_credentials.md are preserved verbatim.")
    args = parser.parse_args()

    only_set: set[str] | None = None
    if args.only:
        only_set = {e.strip() for e in args.only.split(",") if e.strip()}
        # Validate.
        known = {e for e, _ in DEMO_EMAILS}
        unknown = only_set - known
        if unknown:
            print(f"ERROR: unknown demo emails in --only: {unknown}", file=sys.stderr)
            print(f"       valid: {sorted(known)}", file=sys.stderr)
            sys.exit(2)

    rows = asyncio.run(_rotate(only_set))
    _write_credentials(rows, partial=only_set is not None)
    print(f"Rotated {sum(1 for r in rows if r[3])} / {len(rows)} demo accounts"
          f"{' (partial: ' + ','.join(sorted(only_set)) + ')' if only_set else ''}.")
    for email, role, pw, ok in rows:
        if ok:
            print(f"  {role:16s} {email:32s} {pw}")
        else:
            print(f"  {role:16s} {email:32s} SKIPPED (no user row)")
    print(f"Credentials written to {CREDS_PATH}")


if __name__ == "__main__":
    main()
