/** Phase 17C · Mobile — Studio: read-only page list + preview + 1-tap actions. */
import React, { useCallback, useState } from 'react';
import {
  View, Text, StyleSheet, ScrollView, Pressable, Alert,
  Linking,
} from "react-native";
import { Ionicons } from "@expo/vector-icons";
import { useFocusEffect, useRouter } from "expo-router";
import { WebView } from "react-native-webview";

import { api } from "@/src/api";
import { useToast } from "@/src/components/ToastProvider";
import { colors, spacing, radius, font, fontSize } from "@/src/theme";
import { Header } from "@/src/components/widgets";
import { AdminOnlyGate, BrandPill, DesktopHint, CenterLoader } from "./_shared";

const BACKEND = process.env.EXPO_PUBLIC_BACKEND_URL || "";

export default function StudioMobile() {
  return (
    <AdminOnlyGate title="Website Studio">
      <Inner />
    </AdminOnlyGate>
  );
}

function Inner() {
  const { showToast } = useToast();
  const router = useRouter();
  const [rows, setRows] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [preview, setPreview] = useState<any>(null);
  const [busy, setBusy] = useState(false);

  const load = async () => {
    setLoading(true);
    try {
      const r = await api.get("/seo/studio/pages");
      setRows(r.items || []);
    } finally { setLoading(false); }
  };
  useFocusEffect(useCallback(() => { load(); }, []));

  const openPreview = async (p: any) => {
    const full = await api.get(`/seo/studio/pages/${p.id}`);
    setPreview(full);
  };

  const publish = async (p: any) => {
    setBusy(true);
    try {
      await api.post(`/seo/studio/pages/${p.id}/publish`);
      await load();
      if (preview?.id === p.id) await openPreview(p);
      showToast(`${p.title} is now live.`);
    } catch (e: any) {
      showToast(e?.message || "Publish failed.", "error");
    } finally { setBusy(false); }
  };

  const autoFill = async (p: any) => {
    if (!p.target_keyword) {
      Alert.alert("Missing target keyword",
                   "Edit target keyword on desktop first, then auto-fill here.");
      return;
    }
    setBusy(true);
    try {
      const full = await api.get(`/seo/studio/pages/${p.id}`);
      const r = await api.post(`/seo/studio/pages/${p.id}/auto-fill`, {
        business_context: full.business_context || "",
        target_keyword: full.target_keyword || "",
      }, 90000);
      if (r.mocked) {
        Alert.alert("AI unavailable",
                     r.reason || "EMERGENT_LLM_KEY not set.");
      } else {
        Alert.alert("Auto-filled",
                     `${r.count} sections generated by Claude.`);
      }
      if (preview?.id === p.id) await openPreview(p);
    } catch (e: any) {
      Alert.alert("Auto-fill failed", e?.message || "Error");
    } finally { setBusy(false); }
  };

  if (preview) {
    const previewUrl = `${BACKEND}/api/preview/studio/${preview.slug}`;
    const published = preview.status === "published";
    return (
      <View style={styles.root}>
        <Header title={preview.title || "Preview"} />
        <View style={styles.previewBar}>
          <Pressable onPress={() => setPreview(null)}
                      style={styles.backBtn}
                      testID="studio-back">
            <Ionicons name="chevron-back" size={18}
                       color={colors.brand} />
            <Text style={styles.backBtnText}>Pages</Text>
          </Pressable>
          <BrandPill text={preview.status}
                      tone={published ? "green" : "amber"} />
          {published && (
            <Pressable onPress={() => Linking.openURL(previewUrl)}
                        style={styles.linkBtn}
                        testID="studio-open-external">
              <Ionicons name="open-outline" size={16}
                         color={colors.brand} />
            </Pressable>
          )}
        </View>
        {published ? (
          <WebView source={{ uri: previewUrl }}
                    style={{ flex: 1 }} />
        ) : (
          <View style={styles.draftView}>
            <Ionicons name="document-outline" size={28}
                       color={colors.muted} />
            <Text style={styles.draftTitle}>Draft — not yet published</Text>
            <Text style={styles.draftBody}>
              {preview.sections?.length || 0} sections ·{" "}
              target keyword: {preview.target_keyword || "—"}
            </Text>
            <Pressable style={styles.primaryBtn}
                        disabled={busy}
                        onPress={() => publish(preview)}
                        testID="studio-preview-publish">
              <Text style={styles.primaryBtnText}>
                {busy ? "Publishing…" : "Publish"}
              </Text>
            </Pressable>
            <Pressable style={styles.secondaryBtn}
                        disabled={busy}
                        onPress={() => autoFill(preview)}
                        testID="studio-preview-autofill">
              <Text style={styles.secondaryBtnText}>
                {busy ? "Working…" : "AI Auto-Fill"}
              </Text>
            </Pressable>
            <DesktopHint text="Edit sections on desktop for full control." />
          </View>
        )}
      </View>
    );
  }

  return (
    <View style={styles.root}>
      <Header title="Website Studio" />
      <ScrollView contentContainerStyle={{ padding: spacing.lg,
                                             paddingBottom: 60 }}>
        <DesktopHint text="Section editing is desktop-only on mobile. Publish + auto-fill work here." />
        {loading ? <CenterLoader /> : rows.length === 0 ? (
          <View style={styles.empty}>
            <Ionicons name="document-outline" size={28}
                       color={colors.muted} />
            <Text style={styles.emptyTitle}>No pages yet</Text>
            <Text style={styles.emptyBody}>
              Create pages on desktop to see them here.
            </Text>
          </View>
        ) : (
          rows.map((p) => (
            <Pressable key={p.id} style={styles.card}
                        onPress={() => openPreview(p)}
                        testID={`studio-page-${p.id}`}>
              <View style={{ flex: 1, minWidth: 0 }}>
                <Text style={styles.title} numberOfLines={1}>{p.title}</Text>
                <Text style={styles.meta} numberOfLines={1}>
                  /{p.slug} · {p.target_keyword || "no keyword"}
                </Text>
              </View>
              <BrandPill text={p.status}
                          tone={p.status === "published"
                                  ? "green" : "amber"} />
              <Ionicons name="chevron-forward" size={16}
                         color={colors.muted} />
            </Pressable>
          ))
        )}
      </ScrollView>
    </View>
  );
}

const styles = StyleSheet.create({
  root: { flex: 1, backgroundColor: colors.surfaceSecondary },
  empty: { padding: spacing["2xl"], alignItems: "center",
            gap: spacing.sm },
  emptyTitle: { fontFamily: font.bold, fontSize: fontSize.lg,
                 color: colors.onSurface, marginTop: spacing.sm },
  emptyBody: { fontFamily: font.regular, fontSize: fontSize.base,
                color: colors.muted, textAlign: "center" },
  card: {
    flexDirection: "row", alignItems: "center", gap: spacing.sm,
    padding: spacing.md, backgroundColor: colors.surface,
    borderRadius: radius.md, borderWidth: 1,
    borderColor: colors.border, marginBottom: spacing.sm,
  },
  title: { fontFamily: font.bold, fontSize: fontSize.base,
            color: colors.onSurface },
  meta: { fontFamily: font.regular, fontSize: fontSize.sm,
           color: colors.muted, marginTop: 2 },
  previewBar: {
    flexDirection: "row", alignItems: "center", gap: spacing.sm,
    padding: spacing.md, backgroundColor: colors.surface,
    borderBottomWidth: 1, borderBottomColor: colors.border,
  },
  backBtn: {
    flexDirection: "row", alignItems: "center", gap: 4,
    paddingHorizontal: spacing.sm, paddingVertical: 6,
  },
  backBtnText: { fontFamily: font.semibold, fontSize: fontSize.sm,
                  color: colors.brand },
  linkBtn: { marginLeft: "auto", padding: spacing.sm },
  draftView: { padding: spacing.xl, alignItems: "center",
                gap: spacing.md },
  draftTitle: { fontFamily: font.bold, fontSize: fontSize.lg,
                 color: colors.onSurface, marginTop: spacing.sm },
  draftBody: { fontFamily: font.regular, fontSize: fontSize.base,
                color: colors.muted, textAlign: "center" },
  primaryBtn: { backgroundColor: colors.brand, paddingHorizontal: 24,
                 paddingVertical: 12, borderRadius: radius.md },
  primaryBtnText: { fontFamily: font.bold, fontSize: fontSize.base,
                     color: "#fff" },
  secondaryBtn: { backgroundColor: colors.surface,
                   borderWidth: 1, borderColor: colors.brand,
                   paddingHorizontal: 24, paddingVertical: 12,
                   borderRadius: radius.md },
  secondaryBtnText: { fontFamily: font.bold, fontSize: fontSize.base,
                       color: colors.brand },
});
