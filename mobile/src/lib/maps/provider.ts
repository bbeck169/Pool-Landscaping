/**
 * Phase K39b · Feb-2026 — Mobile maps provider resolver.
 *
 * Resolves ``EXPO_PUBLIC_MAPS_PROVIDER`` (default "google") to the
 * active adapter. If ``here`` is requested but the credentials env
 * (``EXPO_PUBLIC_HERE_ACCESS_KEY_ID``) is empty, we log a single
 * warning and fall back to Google — same shape as the K39a web
 * resolver so the two stacks stay predictable.
 *
 * K45 AMENDMENT · Feb-2026 — Binary-presence downgrade.
 *
 *   In addition to the credentials check we now consult the
 *   generated ``heresdkStatus.HERE_BINARIES_PRESENT`` constant. If
 *   HERE mode is requested but the native SDK binaries are missing
 *   from disk (``mobile/heresdk/android/heresdk.aar`` /
 *   ``mobile/heresdk/ios/heresdk.xcframework``) we downgrade to
 *   Google silently. This prevents the K45 white-screen crash that
 *   happened when the HERE JS module loaded successfully but its
 *   native constructor threw because the binaries weren't linked.
 *
 *   ``heresdkStatus.generated.ts`` is regenerated by
 *   ``mobile/scripts/heresdk-check.js`` on every ``yarn install``,
 *   so devs never have to remember to flip it.
 */
import { useMemo } from "react";
import { HERE_BINARIES_PRESENT } from "./heresdkStatus.generated";

let _warned = false;
let _warnedBinaries = false;

export function _computeProvider(env: NodeJS.ProcessEnv = process.env): "google" | "here" {
  const raw = (env.EXPO_PUBLIC_MAPS_PROVIDER || "google").toLowerCase();
  const wanted = raw === "here" ? "here" : "google";
  const hereKeyId = env.EXPO_PUBLIC_HERE_ACCESS_KEY_ID || "";
  if (wanted === "here" && !hereKeyId) {
    if (!_warned) {
      // eslint-disable-next-line no-console
      console.warn(
        "[maps] EXPO_PUBLIC_MAPS_PROVIDER=here but " +
          "EXPO_PUBLIC_HERE_ACCESS_KEY_ID is empty — falling back to " +
          "the Google adapter (react-native-maps).",
      );
      _warned = true;
    }
    return "google";
  }
  // K45 · If HERE is requested but the native binary drop is
  // missing on disk, downgrade to Google. The postinstall hook
  // writes the ``HERE_BINARIES_PRESENT`` constant into
  // ``heresdkStatus.generated.ts`` so this check runs from a bundle
  // constant — no runtime fs access needed.
  if (wanted === "here" && !HERE_BINARIES_PRESENT) {
    if (!_warnedBinaries) {
      // eslint-disable-next-line no-console
      console.warn(
        "[K45/maps] EXPO_PUBLIC_MAPS_PROVIDER=here but the HERE SDK " +
          "native binaries are not present in mobile/heresdk/. " +
          "Falling back to the Google adapter to avoid the K45 " +
          "white-screen crash. Drop android/heresdk.aar + " +
          "ios/heresdk.xcframework and re-run yarn install to enable.",
      );
      _warnedBinaries = true;
    }
    return "google";
  }
  return wanted;
}

/**
 * Stable across a session — env vars are baked at build time on
 * Expo/EAS so we memoize the value.
 */
const _CACHED: "google" | "here" = _computeProvider();

export function useMapsProvider(): "google" | "here" {
  return useMemo(() => _CACHED, []);
}
