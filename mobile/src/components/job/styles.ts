// Chemicals measured in gal/lbs/oz use a 0.5-step dropdown (up to 10); tabs use whole numbers 1..10.
export const STEP_OPTIONS = Array.from({ length: 20 }, (_, i) => String((i + 1) * 0.5));
export const TAB_OPTIONS = Array.from({ length: 10 }, (_, i) => String(i + 1));

// Per-reading dropdown ranges (min, max, step). Chlorine/pH use 0.1 increments.
export const READING_RANGES: Record<string, { min: number; max: number; step: number }> = {
  ph: { min: 6, max: 8.5, step: 0.1 },
  chlorine: { min: 0, max: 20, step: 0.1 },
  combined_chlorine: { min: 0, max: 20, step: 0.1 },
  alkalinity: { min: 0, max: 500, step: 20 },
  calcium_hardness: { min: 0, max: 1000, step: 50 },
  cyanuric: { min: 0, max: 600, step: 10 },
  salt: { min: 0, max: 5000, step: 100 },
  tds: { min: 0, max: 3000, step: 100 },
  phosphates: { min: 0, max: 1000, step: 50 },
  water_temp: { min: 50, max: 105, step: 1 },
};

export const buildRange = (min: number, max: number, step: number) => {
  const dec = step < 1 ? 1 : 0;
  const count = Math.round((max - min) / step);
  return Array.from({ length: count + 1 }, (_, i) => {
    const v = min + i * step;
    return dec ? v.toFixed(1) : String(Math.round(v));
  });
};
export const chemOptions = (unit: string) => (unit === "tabs" ? TAB_OPTIONS : STEP_OPTIONS);
export const readingOptions = (key: string) => {
  const c = READING_RANGES[key];
  return c ? buildRange(c.min, c.max, c.step) : [];
};

