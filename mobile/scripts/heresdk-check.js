#!/usr/bin/env node
/**
 * Phase K39b · Feb-2026 — postinstall guard.
 *
 * Prints a friendly warning when the HERE SDK binaries aren't
 * present.  Exits 0 unconditionally so ``yarn install`` never fails
 * because of an optional-mode dependency — Google mode (the K39b
 * default) does not need HERE binaries.  Docs for the drop live in
 * ``mobile/heresdk/README.md``.
 *
 * K45 · Feb-2026 AMENDMENT — Binary-presence marker.
 *
 *   In addition to the log, we now:
 *     (a) Write a ``.MISSING`` marker file at ``mobile/heresdk/.MISSING``
 *         when binaries are absent (deleted when present).
 *     (b) Regenerate ``mobile/src/lib/maps/heresdkStatus.generated.ts``
 *         with an ``HERE_BINARIES_PRESENT`` constant that the runtime
 *         provider resolver consults to downgrade ``here`` → ``google``.
 *
 *   Together these prevent the K45 white-screen crash where the JS
 *   ``react-native-here-explore`` module loaded successfully but its
 *   native constructor threw at import time because the binaries
 *   weren't linked into the app shell.
 */
const path = require("path");
const fs = require("fs");

const root = path.resolve(__dirname, "..", "heresdk");
const android = path.join(root, "android", "heresdk.aar");
const ios = path.join(root, "ios", "heresdk.xcframework");
const marker = path.join(root, ".MISSING");
const statusFile = path.resolve(
  __dirname,
  "..",
  "src",
  "lib",
  "maps",
  "heresdkStatus.generated.ts",
);

const androidOk = fs.existsSync(android);
const iosOk = fs.existsSync(ios);
const allOk = androidOk && iosOk;

// (a) .MISSING marker inside the heresdk drop folder.
try {
  if (!allOk) {
    // Ensure the heresdk folder exists so we can drop the marker.
    if (!fs.existsSync(root)) {
      fs.mkdirSync(root, { recursive: true });
    }
    const parts = [];
    if (!androidOk) parts.push("android/heresdk.aar");
    if (!iosOk) parts.push("ios/heresdk.xcframework");
    fs.writeFileSync(
      marker,
      "HERE SDK binaries missing at " +
        new Date().toISOString() +
        "\n" +
        "Missing: " +
        parts.join(", ") +
        "\n" +
        "See mobile/heresdk/README.md for the binary drop instructions.\n",
      "utf-8",
    );
  } else if (fs.existsSync(marker)) {
    fs.unlinkSync(marker);
  }
} catch (err) {
  // Never fail the install because of the marker file.
  // eslint-disable-next-line no-console
  console.warn("[K45] failed to update heresdk marker:", err && err.message);
}

// (b) Regenerate the bundled status constant so the runtime
//     provider resolver can consult it without fs access.
try {
  const body =
    "/**\n" +
    " * K45 · Feb-2026 — GENERATED FILE (do not edit by hand).\n" +
    " *\n" +
    " * Regenerated by ``mobile/scripts/heresdk-check.js`` on every\n" +
    " * ``yarn install`` / ``yarn postinstall``. Reports whether the\n" +
    " * ``mobile/heresdk/`` binary drop (``android/heresdk.aar`` and\n" +
    " * ``ios/heresdk.xcframework``) is present on disk at bundle time.\n" +
    " */\n" +
    "export const HERE_BINARIES_PRESENT: boolean = " +
    (allOk ? "true" : "false") +
    ";\n";
  // Only rewrite when the value actually changes — keeps git noise
  // low and avoids retriggering Metro's file-watch loop.
  let prev = "";
  try {
    prev = fs.readFileSync(statusFile, "utf-8");
  } catch {
    prev = "";
  }
  if (prev !== body) {
    fs.writeFileSync(statusFile, body, "utf-8");
  }
} catch (err) {
  // eslint-disable-next-line no-console
  console.warn(
    "[K45] failed to regenerate heresdkStatus.generated.ts:",
    err && err.message,
  );
}

if (!allOk) {
  const missing = [
    !androidOk ? "android/heresdk.aar" : null,
    !iosOk ? "ios/heresdk.xcframework/" : null,
  ]
    .filter(Boolean)
    .join(", ");
  // eslint-disable-next-line no-console
  console.log(
    "\n[K39b] HERE SDK binaries not present (" +
      missing +
      "). HERE mode will render a " +
      '"Map unavailable" placeholder. Follow mobile/heresdk/README.md ' +
      "to enable HERE tiles in a dev-client / EAS build. Google " +
      "mode (default) is unaffected.\n" +
      "[K45] Wrote .MISSING marker + regenerated heresdkStatus.generated.ts " +
      "so the runtime resolver will downgrade here → google.\n",
  );
}
process.exit(0);
